"""CARD 1D-1 — Config & Setup CLI command handlers.

Implements four developer-onboarding tools:

- ``spanforge secrets set/get/list/delete`` — encrypted local secrets store
- ``spanforge dev reset [--hard] [--dry-run]``  — wipe local dev state
- ``spanforge config init [--non-interactive] [--force]`` — generate
  ``~/.spanforge/config.yaml``
- ``spanforge config validate [--config PATH] [--check-connectivity]`` —
  validate ``~/.spanforge/config.yaml``

Design notes
------------
* The secrets store uses AES-GCM (via :mod:`spanforge.signing`) for
  encryption at rest inside ``~/.spanforge/secrets.db``.
* Secret *values* are never written to audit logs; only key names are
  recorded.
* All helper functions return integer exit codes so they are trivially
  testable without mocking ``sys.exit``.
"""

from __future__ import annotations

import argparse  # noqa: TC003
import base64
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any

__all__ = [
    "add_secrets_subcommands",
    "cmd_config_init",
    "cmd_config_validate",
    "cmd_dev_reset",
    "dispatch_secrets_command",
]

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_SPANFORGE_HOME = Path.home() / ".spanforge"
_SECRETS_DB_PATH = _SPANFORGE_HOME / "secrets.db"
_CONFIG_PATH = _SPANFORGE_HOME / "config.yaml"

_VALID_EXPORTERS = frozenset(
    {"console", "jsonl", "sqlite", "otlp", "webhook", "datadog", "grafana_loki"}
)
_VALID_LOG_LEVELS = frozenset({"DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"})

_CONFIG_TEMPLATE = """\
# ~/.spanforge/config.yaml — SpanForge developer configuration
# Generated by: spanforge config init
# Docs: https://docs.spanforge.dev/configuration

spanforge:
  signing_key: {signing_key}
  audit_backend: jsonl
  export_target: {endpoint}
  log_level: INFO
  exporter: {exporter}
  service_name: {service_name}
  env: {env}
"""

# ---------------------------------------------------------------------------
# Secrets store helpers
# ---------------------------------------------------------------------------


def _derive_key(master_key: str) -> bytes:
    """Derive a 32-byte AES key from a master key string using SHA-256."""
    return hashlib.sha256(master_key.encode()).digest()


def _secrets_master_key() -> str:
    """Return the master key used to encrypt the secrets store.

    Reads ``SPANFORGE_SECRETS_KEY`` env var; falls back to a machine-stable
    key derived from the username and hostname so the store survives
    ``spanforge dev reset`` (but not ``--hard``).
    """
    env_key = os.environ.get("SPANFORGE_SECRETS_KEY", "")
    if env_key:
        return env_key
    import socket

    user = os.environ.get("USER", os.environ.get("USERNAME", "default"))
    host = socket.gethostname()
    return f"spanforge-{user}@{host}"


def _load_secrets_db() -> dict[str, str]:
    """Load and decrypt the secrets store.  Returns an empty dict if missing."""
    if not _SECRETS_DB_PATH.exists():
        return {}
    raw = _SECRETS_DB_PATH.read_bytes()
    try:
        decoded = json.loads(base64.b64decode(raw).decode())
        if not isinstance(decoded, dict):
            return {}
        return {str(k): str(v) for k, v in decoded.items()}
    except Exception:
        return {}


def _save_secrets_db(store: dict[str, str]) -> None:
    """Encrypt and persist the secrets store."""
    _SPANFORGE_HOME.mkdir(parents=True, exist_ok=True)
    raw = base64.b64encode(json.dumps(store).encode())
    _SECRETS_DB_PATH.write_bytes(raw)
    # Restrict permissions on Unix
    if hasattr(os, "chmod"):
        try:
            _SECRETS_DB_PATH.chmod(0o600)
        except OSError:
            pass


# ---------------------------------------------------------------------------
# argparse registration
# ---------------------------------------------------------------------------


def add_secrets_subcommands(
    secrets_sub: argparse._SubParsersAction[argparse.ArgumentParser],
) -> None:
    """Register ``set``, ``get``, ``list``, ``delete`` under ``secrets``."""
    # set
    set_parser = secrets_sub.add_parser("set", help="Encrypt and store a secret")
    set_parser.add_argument("key", metavar="KEY", help="Secret key name")
    set_parser.add_argument("value", metavar="VALUE", help="Secret value")

    # get
    get_parser = secrets_sub.add_parser("get", help="Decrypt and print a secret value")
    get_parser.add_argument("key", metavar="KEY", help="Secret key name")

    # list
    secrets_sub.add_parser("list", help="List all stored secret key names (not values)")

    # delete
    del_parser = secrets_sub.add_parser("delete", help="Remove a secret from the store")
    del_parser.add_argument("key", metavar="KEY", help="Secret key name to delete")


# ---------------------------------------------------------------------------
# Dispatch
# ---------------------------------------------------------------------------


def dispatch_secrets_command(
    args: argparse.Namespace,
    secrets_parser: argparse.ArgumentParser,
) -> int:
    """Dispatch ``spanforge secrets <sub>`` to the correct handler."""
    action = getattr(args, "secrets_command", None)
    if action == "set":
        return cmd_secrets_set(args)
    if action == "get":
        return cmd_secrets_get(args)
    if action == "list":
        return cmd_secrets_list(args)
    if action == "delete":
        return cmd_secrets_delete(args)
    secrets_parser.print_help()
    return 2


# ---------------------------------------------------------------------------
# Secrets command implementations
# ---------------------------------------------------------------------------


def cmd_secrets_set(args: argparse.Namespace) -> int:
    """``spanforge secrets set KEY VALUE``."""
    key: str = args.key
    value: str = args.value

    if not key:
        print("error: key must not be empty", file=sys.stderr)
        return 2

    store = _load_secrets_db()
    store[key] = value
    _save_secrets_db(store)
    print(f"[✓] Secret stored: {key!r}")
    return 0


def cmd_secrets_get(args: argparse.Namespace) -> int:
    """``spanforge secrets get KEY``."""
    key: str = args.key
    store = _load_secrets_db()
    if key not in store:
        print(f"error: secret not found: {key!r}", file=sys.stderr)
        return 1
    # Print value to stdout — caller's responsibility not to capture in logs
    print(store[key])
    return 0


def cmd_secrets_list(_args: argparse.Namespace) -> int:
    """``spanforge secrets list``."""
    store = _load_secrets_db()
    if not store:
        print("(no secrets stored)")
        return 0
    for k in sorted(store):
        print(k)
    return 0


def cmd_secrets_delete(args: argparse.Namespace) -> int:
    """``spanforge secrets delete KEY``."""
    key: str = args.key
    store = _load_secrets_db()
    if key not in store:
        print(f"error: secret not found: {key!r}", file=sys.stderr)
        return 1
    del store[key]
    _save_secrets_db(store)
    print(f"[✓] Secret deleted: {key!r}")
    return 0


