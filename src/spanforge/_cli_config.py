def cmd_dev_reset(args: argparse.Namespace) -> int:
    """``spanforge dev reset [--hard] [--dry-run]``."""
    hard: bool = getattr(args, "hard", False)
    dry_run: bool = getattr(args, "dry_run", False)

    targets: list[tuple[str, Path]] = [
        ("local audit store", _SPANFORGE_HOME / "audit.db"),
        ("local secrets store", _SECRETS_DB_PATH),
        ("cached gate results", _SPANFORGE_HOME / "gate_cache.json"),
        ("temp export files", _SPANFORGE_HOME / "exports"),
    ]
    if hard:
        targets.append(("spanforge config", _CONFIG_PATH))

    if hard and not dry_run:
        # Prompt for confirmation
        confirm = _prompt_confirm("This will delete ~/.spanforge/config.yaml. Continue? [y/N] ")
        if not confirm:
            print("Aborted.")
            return 1

    deleted: list[str] = []
    skipped: list[str] = []

    for label, path in targets:
        if path.exists():
            if dry_run:
                print(f"  [dry-run] would delete: {path}  ({label})")
            else:
                _delete_path(path)
                deleted.append(label)
        else:
            skipped.append(label)

    if dry_run:
        would_delete = sum(1 for _, p in targets if p.exists())
        print(f"\nDry-run complete \u2014 {would_delete} item(s) would be deleted.")
        return 0

    if deleted:
        for label in deleted:
            print(f"  [✓] Cleared: {label}")
    else:
        print("  Nothing to clear (stores already empty).")

    print(f"\nReset complete ({len(deleted)} item(s) cleared).")
    return 0


def _prompt_confirm(prompt: str) -> bool:
    """Read a y/N confirmation from stdin.  Returns True for 'y' or 'Y'."""
    try:
        answer = input(prompt).strip().lower()
    except (EOFError, KeyboardInterrupt):
        return False
    else:
        return answer in ("y", "yes")


def _delete_path(path: Path) -> None:
    """Delete a file or directory tree silently."""
    if path.is_dir():
        import shutil

        shutil.rmtree(path, ignore_errors=True)
    elif path.is_file():
        try:
            path.unlink()
        except OSError:
            pass


