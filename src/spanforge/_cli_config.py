def cmd_config_init(args: argparse.Namespace) -> int:
    """``spanforge config init [--non-interactive] [--force]``."""
    non_interactive: bool = getattr(args, "non_interactive", False)
    force: bool = getattr(args, "force", False)

    if _CONFIG_PATH.exists() and not force:
        print(
            f"error: {_CONFIG_PATH} already exists. Use --force to overwrite.",
            file=sys.stderr,
        )
        return 1

    if non_interactive:
        values: dict[str, Any] = _default_config_values()
    else:
        wizard_result = _interactive_config_wizard()
        if wizard_result is None:
            return 1
        values = wizard_result

    _SPANFORGE_HOME.mkdir(parents=True, exist_ok=True)
    _write_config(values)
    print(f"[✓] Config written: {_CONFIG_PATH}")
    print(f"    Exporter:      {values['exporter']}")
    print(f"    Service name:  {values['service_name']}")
    print(f"    Environment:   {values['env']}")
    return 0


def _default_config_values() -> dict[str, Any]:
    """Return default config values for non-interactive mode."""
    signing_key = _generate_signing_key()
    return {
        "signing_key": signing_key,
        "exporter": "console",
        "service_name": "my-service",
        "env": "development",
        "endpoint": "stdout",
        "log_level": "INFO",
    }


def _interactive_config_wizard() -> dict[str, Any] | None:
    """Run an interactive wizard.  Returns values dict or None on abort."""
    print("spanforge config init wizard")
    print("=" * 40)
    try:
        service_name = input("Service name [my-service]: ").strip() or "my-service"
        exporter = input("Exporter [console]: ").strip() or "console"
        if exporter not in _VALID_EXPORTERS:
            print(
                f"[!] Unknown exporter {exporter!r}. Valid: {', '.join(sorted(_VALID_EXPORTERS))}",
                file=sys.stderr,
            )
            return None
        endpoint = input("Export endpoint (URL or file path) [stdout]: ").strip() or "stdout"
        env = input("Environment [development]: ").strip() or "development"
        log_level = (input("Log level [INFO]: ").strip().upper() or "INFO")
        if log_level not in _VALID_LOG_LEVELS:
            log_level = "INFO"
    except (EOFError, KeyboardInterrupt):
        print("\nAborted.", file=sys.stderr)
        return None

    signing_key = _generate_signing_key()
    return {
        "signing_key": signing_key,
        "exporter": exporter,
        "service_name": service_name,
        "env": env,
        "endpoint": endpoint,
        "log_level": log_level,
    }


def _generate_signing_key() -> str:
    """Generate a cryptographically random 32-byte base64 signing key."""
    return base64.urlsafe_b64encode(os.urandom(32)).decode()


def _write_config(values: dict[str, Any]) -> None:
    """Render and write the config YAML."""
    content = _CONFIG_TEMPLATE.format(
        signing_key=values.get("signing_key", ""),
        endpoint=values.get("endpoint", "stdout"),
        exporter=values.get("exporter", "console"),
        service_name=values.get("service_name", "my-service"),
        env=values.get("env", "development"),
    )
    _CONFIG_PATH.write_text(content, encoding="utf-8")
    if hasattr(os, "chmod"):
        try:
            _CONFIG_PATH.chmod(0o600)
        except OSError:
            pass


