def cmd_config_validate(args: argparse.Namespace) -> int:
    """``spanforge config validate [--config PATH] [--check-connectivity]``."""
    config_path_arg: str | None = getattr(args, "config", None)
    check_connectivity: bool = getattr(args, "check_connectivity", False)

    config_path = Path(config_path_arg) if config_path_arg else _CONFIG_PATH

    if not config_path.exists():
        print(f"error: config file not found: {config_path}", file=sys.stderr)
        return 1

    try:
        content = config_path.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot read config: {exc}", file=sys.stderr)
        return 1

    errors = _validate_config_yaml(content)
    if errors:
        print(f"Config validation failed ({len(errors)} error(s)):")
        for err in errors:
            print(f"  - {err}")
        return 1

    print(f"[✓] Config valid: {config_path}")

    if check_connectivity:
        return _check_config_connectivity(content)

    return 0


def _validate_config_yaml(content: str) -> list[str]:
    """Validate config YAML content.  Returns list of error strings."""
    errors: list[str] = []

    # Try to parse YAML with stdlib tomllib fallback or simple key parsing
    parsed = _parse_simple_yaml(content)
    if parsed is None:
        errors.append("Could not parse config file as YAML")
        return errors

    sf = parsed.get("spanforge", {})
    if not isinstance(sf, dict):
        errors.append("'spanforge' block must be a mapping")
        return errors

    # Required: signing_key
    signing_key = sf.get("signing_key", "")
    if not signing_key:
        errors.append("spanforge.signing_key is required")
    elif not isinstance(signing_key, str):
        errors.append("spanforge.signing_key must be a string")

    # Validate exporter if present
    exporter = sf.get("exporter", "console")
    if exporter and exporter not in _VALID_EXPORTERS:
        valid = ', '.join(sorted(_VALID_EXPORTERS))
        errors.append(f"spanforge.exporter {exporter!r} is not valid (valid: {valid})")

    # Validate log_level if present
    log_level = sf.get("log_level", "INFO")
    if log_level and log_level.upper() not in _VALID_LOG_LEVELS:
        errors.append(f"spanforge.log_level {log_level!r} is not valid")

    return errors


def _parse_simple_yaml(content: str) -> dict[str, Any] | None:
    """Parse a simple YAML config using stdlib only (no PyYAML required).

    Supports: top-level keys, nested keys under one level of indentation.
    Returns None on parse failure.
    """
    try:
        result: dict[str, Any] = {}
        current_section: str | None = None
        current_dict: dict[str, Any] = {}

        for line in content.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue

            # Top-level key (no leading spaces)
            if not line.startswith(" ") and ":" in stripped:
                if current_section and current_dict:
                    result[current_section] = current_dict

                key, _, rest = stripped.partition(":")
                key = key.strip()
                rest = rest.strip()

                if not rest:
                    # Section start
                    current_section = key
                    current_dict = {}
                    result[key] = current_dict
                else:
                    current_section = None
                    current_dict = {}
                    result[key] = _coerce_value(rest)

            elif line.startswith("  ") and ":" in stripped:
                # Nested key under current section
                key, _, rest = stripped.partition(":")
                key = key.strip()
                rest = rest.strip()
                if current_section is not None:
                    current_dict[key] = _coerce_value(rest)

    except Exception:
        return None
    else:
        return result


def _coerce_value(raw: str) -> Any:  # noqa: PLR0911
    """Coerce a YAML scalar value string to Python type."""
    lower = raw.lower()
    if lower == "true":
        return True
    if lower == "false":
        return False
    if lower in ("null", "~", ""):
        return None
    # Try int, then float
    try:
        return int(raw)
    except ValueError:
        pass
    try:
        return float(raw)
    except ValueError:
        pass
    # Strip surrounding quotes
    if (raw.startswith('"') and raw.endswith('"')) or (raw.startswith("'") and raw.endswith("'")):
        return raw[1:-1]
    return raw


def _check_config_connectivity(content: str) -> int:
    """Attempt to connect to the configured backend.  Returns 0 or 2."""
    parsed = _parse_simple_yaml(content) or {}
    sf = parsed.get("spanforge", {}) if isinstance(parsed.get("spanforge"), dict) else {}
    exporter = sf.get("exporter", "console")
    endpoint = sf.get("export_target", sf.get("endpoint", ""))

    if exporter in ("console", "jsonl", "sqlite", ""):
        print(f"[✓] Connectivity: exporter={exporter!r} — no network check needed")
        return 0

    if exporter == "otlp" and endpoint:
        import socket
        from urllib.parse import urlparse

        try:
            parsed_url = urlparse(str(endpoint))
            host = parsed_url.hostname or "localhost"
            port = parsed_url.port or 4317
            conn = socket.create_connection((host, port), timeout=3)
        except OSError as exc:
            print(f"[✗] Connectivity: OTLP connection failed: {exc}", file=sys.stderr)
            return 2
        else:
            conn.close()
            print(f"[✓] Connectivity: OTLP endpoint {host}:{port} reachable")
            return 0

    print(f"[!] Connectivity: exporter={exporter!r} — skipping check (no endpoint to probe)")
    return 0
